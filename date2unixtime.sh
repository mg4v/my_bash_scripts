#!/bin/bash

# Название: date2unixtime.sh
# Назначение: преобразует дату в формате "ГГГГ-ММ-ДД, ЧЧ:ММ:СС" в Unix timestamp

# Показываем формат ввода
echo "Введите дату и время в формате: ГГГГ-ММ-ДД, ЧЧ:ММ:СС"
echo "Пример: 2024-06-05, 15:34:05"
read -r input

# Удаляем лишние пробелы и нормализуем ввод (убираем пробел после запятой, если есть)
# Ожидаем формат: YYYY-MM-DD, HH:MM:SS → преобразуем в YYYY-MM-DD HH:MM:SS
clean_input=$(echo "$input" | sed 's/, */ /')

# Проверяем, соответствует ли ввод шаблону: YYYY-MM-DD HH:MM:SS
if ! [[ "$clean_input" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}[[:space:]][0-9]{2}:[0-9]{2}:[0-9]{2}$ ]]; then
  echo "Ошибка: неверный формат. Требуется: ГГГГ-ММ-ДД, ЧЧ:ММ:СС"
  exit 1
fi

# Определяем ОС и используем соответствующую команду
if [[ "$(uname)" == "Darwin" ]]; then
  # macOS: используем date с -j и форматом
  unixtime=$(date -j -f "%Y-%m-%d %H:%M:%S" "$clean_input" "+%s" 2>/dev/null)
else
  # Linux: используем date -d
  unixtime=$(date -d "$clean_input" "+%s" 2>/dev/null)
fi

# Проверяем, удалось ли разобрать дату
if [ -z "$unixtime" ]; then
  echo "Ошибка: не удалось распознать дату. Проверьте корректность ввода."
  exit 1
fi

# Выводим результат
echo "Unix timestamp: $unixtime"