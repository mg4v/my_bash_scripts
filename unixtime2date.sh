#!/bin/bash

# Название: unixtime2date.sh
# Назначение: преобразует Unix timestamp (в секундах или миллисекундах) в формат "ГГГГ-ММ-ДД, ЧЧ:ММ:СС"
# Особенность: автоматически определяет, переданы секунды или миллисекунды, и корректирует значение

# Проверяем, передан ли аргумент
if [ -z "$1" ]; then
  echo "Ошибка: не указан timestamp."
  echo "Использование: $0 <unixtime>"
  exit 1
fi

# Извлекаем только цифры
timestamp=$(echo "$1" | sed 's/[^0-9]//g')

# Проверяем, что получилось
if [ -z "$timestamp" ] || [ "$timestamp" -le 0 ] 2>/dev/null; then
  echo "Ошибка: укажите положительное числовое значение."
  exit 1
fi

# Определяем длину
len=${#timestamp}

# Если больше 10 цифр — вероятно, это миллисекунды (13 цифр) или микросекунды
if [ $len -gt 10 ]; then
  # Делим на 1000, используя целочисленное деление
  # Bash не поддерживает дроби, поэтому просто убираем последние 3 цифры
  timestamp=${timestamp%???}  # удаляем последние 3 символа
fi

# Проверяем, что не получилось пусто
if [ -z "$timestamp" ]; then
  echo "Ошибка: слишком короткое значение после преобразования."
  exit 1
fi

# Повторная проверка — вдруг остался 0
if [ "$timestamp" -eq 0 ] 2>/dev/null; then
  echo "Ошибка: timestamp не может быть нулевым после преобразования."
  exit 1
fi

# Определяем ОС и используем соответствующую команду
if [[ "$(uname)" == "Darwin" ]]; then
  # macOS
  date -r "$timestamp" +"%Y-%m-%d, %H:%M:%S" 2>/dev/null
else
  # Linux
  date -d "@$timestamp" +"%Y-%m-%d, %H:%M:%S" 2>/dev/null
fi

# Проверка результата
if [ $? -ne 0 ]; then
  echo "Ошибка: не удалось преобразовать timestamp '$timestamp' в дату."
  exit 1
fi